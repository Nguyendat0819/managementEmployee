CREATE SCHEMA IF NOT EXISTS hr_service;

CREATE TABLE IF NOT EXISTS hr_service.leave_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40),
    name VARCHAR(100) NOT NULL,
    max_days_per_year INTEGER,
    is_deleted BOOLEAN,
    carryover_days INTEGER,
    paid_leave BOOLEAN,
    require_document BOOLEAN,
    description VARCHAR(1000),
    created_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_at TIMESTAMP,
    updated_by VARCHAR(100)
);

ALTER TABLE hr_service.leave_types
    ADD COLUMN IF NOT EXISTS code VARCHAR(40),
    ADD COLUMN IF NOT EXISTS carryover_days INTEGER,
    ADD COLUMN IF NOT EXISTS paid_leave BOOLEAN,
    ADD COLUMN IF NOT EXISTS require_document BOOLEAN,
    ADD COLUMN IF NOT EXISTS description VARCHAR(1000);

UPDATE hr_service.leave_types SET code = 'TYPE-' || id WHERE code IS NULL OR BTRIM(code) = '';
UPDATE hr_service.leave_types SET max_days_per_year = 0 WHERE max_days_per_year IS NULL;
UPDATE hr_service.leave_types SET is_deleted = FALSE WHERE is_deleted IS NULL;
UPDATE hr_service.leave_types SET carryover_days = 0 WHERE carryover_days IS NULL;
UPDATE hr_service.leave_types SET paid_leave = TRUE WHERE paid_leave IS NULL;
UPDATE hr_service.leave_types SET require_document = FALSE WHERE require_document IS NULL;

ALTER TABLE hr_service.leave_types
    ALTER COLUMN code SET NOT NULL,
    ALTER COLUMN max_days_per_year SET DEFAULT 0,
    ALTER COLUMN max_days_per_year SET NOT NULL,
    ALTER COLUMN is_deleted SET DEFAULT FALSE,
    ALTER COLUMN is_deleted SET NOT NULL,
    ALTER COLUMN carryover_days SET DEFAULT 0,
    ALTER COLUMN carryover_days SET NOT NULL,
    ALTER COLUMN paid_leave SET DEFAULT TRUE,
    ALTER COLUMN paid_leave SET NOT NULL,
    ALTER COLUMN require_document SET DEFAULT FALSE,
    ALTER COLUMN require_document SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_leave_types_active_code
    ON hr_service.leave_types (UPPER(code))
    WHERE is_deleted = FALSE;

CREATE TABLE IF NOT EXISTS hr_service.leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_code VARCHAR(40),
    requester_user_id BIGINT,
    employee_code VARCHAR(255) NOT NULL,
    type BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    total_days NUMERIC(8, 2) NOT NULL,
    reason TEXT,
    evidence_url VARCHAR(2000),
    status VARCHAR(50) NOT NULL,
    approver_code VARCHAR(255),
    approved_at TIMESTAMP,
    reject_reason TEXT,
    created_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_at TIMESTAMP,
    updated_by VARCHAR(100)
);

ALTER TABLE hr_service.leave_requests
    ADD COLUMN IF NOT EXISTS request_code VARCHAR(40),
    ADD COLUMN IF NOT EXISTS requester_user_id BIGINT,
    ADD COLUMN IF NOT EXISTS evidence_url VARCHAR(2000);

UPDATE hr_service.leave_requests
SET request_code = 'NP-' || COALESCE(EXTRACT(YEAR FROM created_at)::INTEGER, EXTRACT(YEAR FROM CURRENT_DATE)::INTEGER)
                   || '-' || LPAD(id::TEXT, 8, '0')
WHERE request_code IS NULL OR BTRIM(request_code) = '';

UPDATE hr_service.leave_requests SET status = 'PENDING' WHERE status IN ('Chờ duyệt', 'WAITING', 'PENDING');
UPDATE hr_service.leave_requests SET status = 'APPROVED' WHERE status IN ('Đã duyệt', 'APPROVED');
UPDATE hr_service.leave_requests SET status = 'REJECTED' WHERE status IN ('Từ chối', 'REJECTED');
UPDATE hr_service.leave_requests SET status = 'CANCELLED' WHERE status IN ('Đã hủy', 'CANCELLED');

ALTER TABLE hr_service.leave_requests
    ALTER COLUMN request_code SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_leave_requests_request_code
    ON hr_service.leave_requests (request_code);
CREATE INDEX IF NOT EXISTS idx_leave_requests_owner_created
    ON hr_service.leave_requests (requester_user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_leave_requests_employee_dates
    ON hr_service.leave_requests (employee_code, start_date, end_date);
CREATE INDEX IF NOT EXISTS idx_leave_requests_status_created
    ON hr_service.leave_requests (status, created_at DESC);

CREATE TABLE IF NOT EXISTS hr_service.leave_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code VARCHAR(255),
    requester_user_id BIGINT,
    type BIGINT NOT NULL,
    balance_year INTEGER NOT NULL,
    total_days NUMERIC(8, 2) NOT NULL DEFAULT 0,
    used_days NUMERIC(8, 2) NOT NULL DEFAULT 0
);

ALTER TABLE hr_service.leave_balances
    ADD COLUMN IF NOT EXISTS requester_user_id BIGINT,
    ADD COLUMN IF NOT EXISTS balance_year INTEGER,
    ADD COLUMN IF NOT EXISTS total_days NUMERIC(8, 2),
    ADD COLUMN IF NOT EXISTS used_days NUMERIC(8, 2);

UPDATE hr_service.leave_balances balance
SET balance_year = EXTRACT(YEAR FROM CURRENT_DATE)::INTEGER,
    total_days = COALESCE(leave_type.max_days_per_year, 0),
    used_days = COALESCE(balance.used_days, 0)
FROM hr_service.leave_types leave_type
WHERE balance.type = leave_type.id
  AND (balance.balance_year IS NULL OR balance.total_days IS NULL OR balance.used_days IS NULL);

UPDATE hr_service.leave_balances SET balance_year = EXTRACT(YEAR FROM CURRENT_DATE)::INTEGER WHERE balance_year IS NULL;
UPDATE hr_service.leave_balances SET total_days = 0 WHERE total_days IS NULL;
UPDATE hr_service.leave_balances SET used_days = 0 WHERE used_days IS NULL;

ALTER TABLE hr_service.leave_balances
    ALTER COLUMN balance_year SET NOT NULL,
    ALTER COLUMN total_days SET DEFAULT 0,
    ALTER COLUMN total_days SET NOT NULL,
    ALTER COLUMN used_days SET DEFAULT 0,
    ALTER COLUMN used_days SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_leave_balances_owner_type_year
    ON hr_service.leave_balances (requester_user_id, type, balance_year);
CREATE UNIQUE INDEX IF NOT EXISTS uq_leave_balances_legacy_employee_type_year
    ON hr_service.leave_balances (employee_code, type, balance_year)
    WHERE requester_user_id IS NULL;
CREATE INDEX IF NOT EXISTS idx_leave_balances_employee_type_year
    ON hr_service.leave_balances (employee_code, type, balance_year);

CREATE TABLE IF NOT EXISTS hr_service.holidays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holiday_date DATE NOT NULL,
    holiday_date_end DATE,
    name VARCHAR(200) NOT NULL,
    holiday_type VARCHAR(50) NOT NULL,
    notes VARCHAR(500),
    is_deleted BOOLEAN,
    created_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_at TIMESTAMP,
    updated_by VARCHAR(100)
);

ALTER TABLE hr_service.holidays
    ADD COLUMN IF NOT EXISTS holiday_date_end DATE,
    ADD COLUMN IF NOT EXISTS notes VARCHAR(500),
    ADD COLUMN IF NOT EXISTS is_deleted BOOLEAN;

UPDATE hr_service.holidays SET holiday_date_end = holiday_date WHERE holiday_date_end IS NULL;
UPDATE hr_service.holidays SET is_deleted = FALSE WHERE is_deleted IS NULL;

ALTER TABLE hr_service.holidays
    ALTER COLUMN holiday_date_end SET NOT NULL,
    ALTER COLUMN is_deleted SET DEFAULT FALSE,
    ALTER COLUMN is_deleted SET NOT NULL;

CREATE INDEX IF NOT EXISTS idx_holidays_active_dates
    ON hr_service.holidays (holiday_date, holiday_date_end)
    WHERE is_deleted = FALSE;
