    ADD COLUMN IF NOT EXISTS total_employer_cost NUMERIC DEFAULT 0;

UPDATE hr_service.payroll_runs
SET total_employer_cost = 0
WHERE total_employer_cost IS NULL;

ALTER TABLE hr_service.payslips
    ADD COLUMN IF NOT EXISTS unemployment_insurance NUMERIC DEFAULT 0,
    ADD COLUMN IF NOT EXISTS employer_social_insurance NUMERIC DEFAULT 0,
    ADD COLUMN IF NOT EXISTS employer_health_insurance NUMERIC DEFAULT 0,
    ADD COLUMN IF NOT EXISTS employer_unemployment_insurance NUMERIC DEFAULT 0;

UPDATE hr_service.payslips
SET unemployment_insurance = COALESCE(unemployment_insurance, 0),
    employer_social_insurance = COALESCE(employer_social_insurance, 0),
    employer_health_insurance = COALESCE(employer_health_insurance, 0),
    employer_unemployment_insurance = COALESCE(employer_unemployment_insurance, 0);

ALTER TABLE hr_service.payslips
    ALTER COLUMN unemployment_insurance SET NOT NULL,
    ALTER COLUMN unemployment_insurance SET DEFAULT 0,
    ALTER COLUMN employer_social_insurance SET NOT NULL,
    ALTER COLUMN employer_social_insurance SET DEFAULT 0,
    ALTER COLUMN employer_health_insurance SET NOT NULL,
    ALTER COLUMN employer_health_insurance SET DEFAULT 0,
    ALTER COLUMN employer_unemployment_insurance SET NOT NULL,
    ALTER COLUMN employer_unemployment_insurance SET DEFAULT 0;

CREATE TABLE IF NOT EXISTS hr_service.payroll_holidays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    holiday_type VARCHAR(80) NOT NULL,
    holiday_date DATE NOT NULL,
    holiday_date_end DATE NOT NULL,
    notes VARCHAR(500),
    created_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_at TIMESTAMP,
    updated_by VARCHAR(100),
    CONSTRAINT ck_payroll_holidays_date_range CHECK (holiday_date_end >= holiday_date)
);

CREATE INDEX IF NOT EXISTS idx_payroll_holidays_date_range
    ON hr_service.payroll_holidays (holiday_date, holiday_date_end);
