-- Repair databases where leave_balances predates the workflow migration and id has no generator.
DO $$
DECLARE
    id_default TEXT;
    id_is_identity TEXT;
    id_sequence TEXT;
    next_id BIGINT;
BEGIN
    LOCK TABLE hr_service.leave_balances IN ACCESS EXCLUSIVE MODE;

    SELECT column_default, is_identity
      INTO id_default, id_is_identity
      FROM information_schema.columns
     WHERE table_schema = 'hr_service'
       AND table_name = 'leave_balances'
       AND column_name = 'id';

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Column hr_service.leave_balances.id does not exist';
    END IF;

    IF id_is_identity = 'NO' AND id_default IS NULL THEN
        ALTER TABLE hr_service.leave_balances
            ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;

    id_sequence := pg_get_serial_sequence('hr_service.leave_balances', 'id');
    IF id_sequence IS NOT NULL THEN
        SELECT COALESCE(MAX(id), 0) + 1
          INTO next_id
          FROM hr_service.leave_balances;
        PERFORM setval(id_sequence::regclass, next_id, FALSE);
    END IF;
END $$;
