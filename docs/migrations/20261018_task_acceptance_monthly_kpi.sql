ALTER TABLE hr_service.employee_tasks
    ADD COLUMN IF NOT EXISTS acceptance_criteria VARCHAR(4000) NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS period_month DATE,
    ADD COLUMN IF NOT EXISTS weight NUMERIC(7, 2) NOT NULL DEFAULT 1.00,
    ADD COLUMN IF NOT EXISTS approved_percent INTEGER;

UPDATE hr_service.employee_tasks
SET period_month = date_trunc('month', COALESCE(due_date, created_at::date, CURRENT_DATE)::timestamp)::date
WHERE period_month IS NULL;

UPDATE hr_service.employee_tasks
SET acceptance_criteria = COALESCE(NULLIF(description, ''), title)
WHERE acceptance_criteria = '';

UPDATE hr_service.employee_tasks
SET approved_percent = completion_percent
WHERE status = 'APPROVED'
  AND approved_percent IS NULL
  AND completion_percent IS NOT NULL;

ALTER TABLE hr_service.employee_tasks
    ALTER COLUMN period_month SET DEFAULT date_trunc('month', CURRENT_DATE)::date,
    ALTER COLUMN period_month SET NOT NULL;

CREATE INDEX IF NOT EXISTS employee_tasks_period_month_employee_idx
    ON hr_service.employee_tasks(period_month, employee_code);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'employee_tasks_weight_check') THEN
        ALTER TABLE hr_service.employee_tasks
            ADD CONSTRAINT employee_tasks_weight_check CHECK (weight > 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'employee_tasks_period_month_check') THEN
        ALTER TABLE hr_service.employee_tasks
            ADD CONSTRAINT employee_tasks_period_month_check CHECK (period_month = date_trunc('month', period_month)::date);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'employee_tasks_approved_percent_check') THEN
        ALTER TABLE hr_service.employee_tasks
            ADD CONSTRAINT employee_tasks_approved_percent_check CHECK (approved_percent IS NULL OR approved_percent BETWEEN 0 AND 100);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS hr_service.employee_task_progress_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES hr_service.employee_tasks(id) ON DELETE CASCADE,
    proposed_percent INTEGER CHECK (proposed_percent BETWEEN 0 AND 100),
    result VARCHAR(4000) NOT NULL,
    evidence_links JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(evidence_links) = 'array'),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    submitted_at TIMESTAMP NOT NULL,
    reviewed_at TIMESTAMP,
    reviewed_by VARCHAR(255),
    review_comment VARCHAR(1000),
    created_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_at TIMESTAMP,
    updated_by VARCHAR(100)
);

ALTER TABLE hr_service.employee_task_progress_submissions
    ALTER COLUMN proposed_percent DROP NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS employee_task_progress_one_pending_idx
    ON hr_service.employee_task_progress_submissions(task_id)
    WHERE status = 'PENDING';

CREATE INDEX IF NOT EXISTS employee_task_progress_history_idx
    ON hr_service.employee_task_progress_submissions(task_id, submitted_at DESC);

INSERT INTO hr_service.employee_task_progress_submissions (
    task_id, proposed_percent, result, status, submitted_at, reviewed_at, reviewed_by, review_comment,
    created_at, created_by, updated_at, updated_by
)
SELECT t.id,
       t.completion_percent,
       '',
       CASE t.status WHEN 'APPROVED' THEN 'APPROVED' WHEN 'REJECTED' THEN 'REJECTED' ELSE 'PENDING' END,
       COALESCE(t.submitted_at, t.created_at, CURRENT_TIMESTAMP),
       t.reviewed_at,
       t.reviewed_by,
       t.review_comment,
       t.created_at,
       t.created_by,
       t.updated_at,
       t.updated_by
FROM hr_service.employee_tasks t
WHERE t.status IN ('SUBMITTED', 'APPROVED', 'REJECTED')
  AND (t.completion_percent IS NOT NULL OR t.status = 'SUBMITTED')
  AND NOT EXISTS (
      SELECT 1
      FROM hr_service.employee_task_progress_submissions p
      WHERE p.task_id = t.id
  );
